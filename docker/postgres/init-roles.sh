#!/bin/sh
# 首次建立資料庫時執行（postgres 映像的 /docker-entrypoint-initdb.d）。見 docs/adr/0001-multi-tenancy.md：
# - fitness_owner：擁有資料表，跑 migration 與平台工具
# - fitness_app：應用程式連線用，只有資料讀寫權限，受 RLS 限制（NOSUPERUSER、NOBYPASSRLS）
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres <<SQL
CREATE ROLE ${DB_OWNER_USER} LOGIN PASSWORD '${DB_OWNER_PASSWORD}' NOSUPERUSER NOBYPASSRLS;
CREATE ROLE ${DB_APP_USER} LOGIN PASSWORD '${DB_APP_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE DATABASE ${DB_NAME} OWNER ${DB_OWNER_USER};
SQL

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$DB_NAME" <<SQL
REVOKE ALL ON SCHEMA public FROM PUBLIC;
ALTER SCHEMA public OWNER TO ${DB_OWNER_USER};
GRANT USAGE ON SCHEMA public TO ${DB_APP_USER};
GRANT CONNECT ON DATABASE ${DB_NAME} TO ${DB_APP_USER};
SQL
